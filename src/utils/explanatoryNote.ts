import { resolveContourGeometry } from '../engine/calculator';
import {
  CalculationInput,
  CalculationResult,
  FillerCatalogItem,
} from '../types/calculator';

export function generateExplanatoryNote(
  result: CalculationResult,
  input: CalculationInput,
  filler: FillerCatalogItem
): string {
  const { bag } = result;
  const geom = resolveContourGeometry(input);
  const ratioText =
    result.actualRatioWH >= 3.0
      ? `3:1 (фактически ${result.actualRatioWH.toFixed(2)}:1 — профиль открытой площадки)`
      : result.actualRatioWH >= 2.0
        ? `2:1 (фактически ${result.actualRatioWH.toFixed(2)}:1 — профиль стеснённых условий)`
        : `${result.actualRatioWH.toFixed(2)}:1 (ВНИМАНИЕ: ниже минимально допустимого 2:1!)`;

  const swlText =
    result.effectiveSwlKg !== null
      ? `${(result.effectiveSwlKg / 1000).toFixed(2)} т (${result.effectiveSwlKg} кг)`
      : '______________ (БРН требует уточнения по паспорту)';

  const fabricText =
    bag.fabricDensityGsm !== null
      ? `${bag.fabricDensityGsm} г/м²`
      : '______________ (рекомендуется 160–200 г/м² с УФ-стабилизацией)';

  const electrostaticNote =
    input.hazardZone === 'explosive'
      ? 'Объект относится ко взрывоопасной зоне 1/2 (НПЗ, ГСМ): обязательны МКР Типа C (токопроводящая сетка с сопротивлением < 10^7 Ом и заземлением каждого мешка контуром) или Типа D (диссипативные волокна, IEC 61340-4-4).'
      : 'Вне взрывоопасных зон допускается применение стандартных полипропиленовых МКР Типа A с УФ-стабилизацией (добавка HALS-стабилизаторов).';

  const statusText =
    result.status === 'VALID'
      ? 'ПОЛНОЕ СООТВЕТСТВИЕ (все инженерные проверки пройдены)'
      : result.status === 'WARNING'
        ? 'ДОПУСТИМО С ИНЖЕНЕРНЫМИ ОГОВОРКАМИ (см. перечень предупреждений)'
        : 'НЕ ПРОХОДИТ НОРМАТИВНЫЕ ОГРАНИЧЕНИЯ (требуется пересмотр параметров)';

  const lines: string[] = [
    'ПОЯСНИТЕЛЬНАЯ ЗАПИСКА (ФРАГМЕНТ РАЗДЕЛА ПО ПРОЕКТИРОВАНИЮ ЗОК ИЗ МКР)',
    '',
    '1. Нормативно-правовое обоснование:',
    'Защитная ограждающая конструкция (ЗОК) из мягких полипропиленовых контейнеров (МКР / биг-бэгов) с сыпучим минеральным наполнителем запроектирована в соответствии с пп. 1.1, 3.1.2, 3.1.7, 4.2, 6.1.6, 7.1.3, 7.6.1, 8.1.1, 9.1.1.3, 9.1.2.4, 9.5.1, 9.5.3, 10.5 и 11.3 СП 542.1325800.2024 «Защитные ограждающие конструкции от беспилотных летательных аппаратов. Правила проектирования» (утв. приказом Минстроя России от 25.12.2024 № 910/пр) с учётом Изменения № 1 (утв. приказом Минстроя России от 25.08.2026 № 566/пр).',
    'В соответствии с п. 9.1.1.3 СП 542.1325800.2024 уровень ответственности ЗОК при сроке эксплуатации до 10 лет не нормируется. Конструкция предназначена для пассивной противоосколочной защиты боковой проекции и уязвимых нижних узлов технологического оборудования.',
    '',
    '2. Геометрические параметры и расчётная схема трапеции:',
    `- Ширина основания стены W_осн: ${geom.baseWidthM.toFixed(2)} м`,
    `- Проектная минимальная высота H_min: ${geom.minHeightM.toFixed(2)} м`,
    `- Фактическая расчётная высота H_факт: ${result.hTotalFactM.toFixed(2)} м (${result.tiersCount} яр. по ${result.hFactM.toFixed(3)} м)`,
    `- Ширина верхнего среза (гребня) W_верх: ${result.crestWidthM.toFixed(2)} м (${result.crestRowsCount} ряд(а) МКР)`,
    `- Средний периметр укрепления P_ср: ${geom.avgPerimeterM.toFixed(2)} м`,
    `- Соотношение основания к высоте W:H: ${ratioText}; расчётный угол откоса: ${result.slopeAngleDeg.toFixed(1)}°`,
    input.mode === 'object'
      ? `- Горизонтальный отступ от защищаемого объекта d_отст: ${input.objectContour.offsetM.toFixed(2)} м (норма >= 1,5 м по пп. 3.1.13, 9.5.3 СП 542.1325800.2024)`
      : '- Горизонтальный отступ безопасности от внутреннего края стены до защищаемого объекта принимать не менее 1,5 м (для РВС — 2,0–3,0 м).',
    '',
    '3. Характеристики выбранного типоразмера МКР и наполнителя:',
    `- Производитель / модель: ${bag.manufacturer} (${bag.dimensionsCm.length}×${bag.dimensionsCm.width}×${bag.dimensionsCm.height} см)`,
    `- Плотность полипропиленовой ткани: ${fabricText}; коэффициент запаса прочности строп SF >= 5:1 (ГОСТ Р 52564-2006, ГОСТ 30090-93, ГОСТ 32522-2013, ГОСТ 34875-2022, ГОСТ ISO 21898-2013)`,
    `- Паспортная БРН (SWL): ${swlText}; предел штабелирования: до ${result.allowedMaxTiers} ярусов`,
    `- Наполнитель: ${filler.name} с расчётной насыпной плотностью ${input.fillerDensityKgM3} кг/м³`,
    `- Рекомендация по оболочке: ${filler.bagRecommendation}`,
    `- ${electrostaticNote}`,
    `- Режим заполнения одного МКР: V_доп = ${result.vAllowedM3.toFixed(3)} м³, масса груза m_МКР = ${result.mBagKg.toFixed(1)} кг (${result.swlUsagePct !== null ? `${result.swlUsagePct.toFixed(1)}% от БРН` : 'БРН не задана'}), высота засыпки в ярусе h_факт = ${result.hFactM.toFixed(3)} м (${input.heightMode === 'fit_h_min' ? 'подгонка высоты засыпки под H_min' : `лимит по ${Math.round(input.fillHeightRatio * 100)}% высоты / БРН`}).`,
    '',
    '4. Сводная ведомость объёмов и материалов (дискретный поярусный расчёт):',
    `- Схема рядов по ярусам (снизу вверх): ${result.rowsPerTier.join('–')} (всего ${result.sectionBagsCount} шт. в поперечном сечении; ${result.bagsPerMeter.toFixed(2)} шт./пог. м)`,
    `- Потребное количество МКР (дискретная раскладка): ${result.nBagsDiscrete} шт. (для справки: объёмная прикидка N_объём = ${result.nBagsVolume} шт., расхождение ${result.methodDiffPct >= 0 ? '+' : ''}${result.methodDiffPct.toFixed(1)}%)`,
    `- Суммарный объём наполнителя (с коэфф. потерь ${input.lossFactor.toFixed(2)}): ${result.totalFillerM3.toFixed(1)} м³`,
    `- Суммарная масса наполнителя: ${result.totalFillerTons.toFixed(1)} т (с пустой тарой: ~${result.totalGrossTons.toFixed(1)} т)`,
    `- Выемка грунта под связующую траншею глубиной 0,15 м: ${result.trenchVolumeM3.toFixed(1)} м³`,
    input.includeTarp
      ? `- Площадь защитного УФ-полога: ${result.tarpAreaM2.toFixed(1)} м² (защита от УФ-деградации полипропилена на срок до 10 лет и от морозного пучения)`
      : '- Защитный УФ-полог: не предусматривается проектом (временное сооружение / бестентовое исполнение)',
    '',
    '5. Конструктивно-технологические требования к возведению и эксплуатации:',
    '- Укладка контейнеров выполняется с перевязкой вертикальных швов на 1/2 длины по принципу кирпичной кладки (исключение сквозных каналов и эффекта «стопки монет» по п. 9.5.3 СП 542.1325800.2024).',
    '- Под нижним ярусом при высоте стены > 1,0 м устраивается связующая (анкерная) траншея глубиной 10–15 см с подготовкой грунтового основания по СП 22.13330 и щебёночной дренажной отмосткой.',
    '- Наполнение выполняется на твёрдом упоре не более чем до 85% высоты корпуса; при применении виброуплотнения — амплитуда 1,2–2,0 мм, частота 10–50 Гц, длительность 1,5–2,0 мин.',
    input.includeTarp
      ? '- Готовая стена укрывается водонепроницаемым УФ-защищённым полипропиленовым пологом с закреплением люверсами; эксплуатационный осмотр проводится не реже 1 раза в месяц (п. 11.3 СП 542.1325800.2024).'
      : '- Сооружение эксплуатируется в открытом режиме без полога; периодический осмотр состояния ткани МКР проводится не реже 1 раза в 2 недели.',
    '',
    `Статус инженерной проверки варианта: ${statusText}.`,
  ];

  if (result.checks.length > 0) {
    lines.push('Перечень выявленных замечаний и предписаний:');
    for (const chk of result.checks) {
      lines.push(`  • [${chk.code} | ${chk.level}] ${chk.message}`);
    }
  }

  return lines.join('\n');
}
