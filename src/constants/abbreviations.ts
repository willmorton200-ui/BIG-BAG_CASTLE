/**
 * Возвращает подсказку по ключу аббревиатуры (без учёта регистра)
 */
export function getAbbrTooltip(abbr: string): string | undefined {
  if (ABBREVIATIONS[abbr]) return ABBREVIATIONS[abbr];
  const upper = abbr.toUpperCase();
  if (ABBREVIATIONS[upper]) return ABBREVIATIONS[upper];
  return undefined;
}
